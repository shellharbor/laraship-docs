  await page.locator('#tools').getByRole('button', { name: 'Kubernetes', exact: true }).click();
  const tools = page.getByRole('region', { name: 'Kubernetes command builder' });
  for (const [label, value] of [['Kubernetes application name', 'shop'], ['Existing namespace', 'shop'], ['Immutable ConfigMap name', 'shop-config-v1'], ['Immutable Secret name', 'shop-secret-v1'], ['Release revision', 'release-1'], ['Versioned application image', 'registry.example.com/shop:1.0'], ['Explicit kubectl context', 'production'], ['Kubeconfig file path', '/root/kubeconfig']]) await tools.getByLabel(label).fill(value);
  await tools.getByLabel('Web replicas').fill('3');
  await tools.getByLabel('Registry Secret name').fill('registry-access');
  await tools.getByRole('checkbox', { name: /^Enable Kubernetes queue worker/ }).check();
